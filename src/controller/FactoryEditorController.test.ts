import { createProgressStore, projectsKey } from '../model/ProgressRepository'
import { describe, expect, it } from 'vitest'
import { FactoryEditorController, FactoryProjectsController } from './FactoryEditorController'
import { factoryUnits } from '../model/factory/unlocks'
import type { Block, RunInput } from '../model/factory/types'

const progress = { stages: Object.fromEntries(factoryUnits.flat().map(s => [s.id, { completed: true, bestStars: 0, lastProgram: [] }])) }
const input = (): RunInput => ({ start: { belt: [], piles: { leaf: [], moon: [], sun: [] } }, program: { main: [], functions: [] }, orders: [], target: 0, signals: [] })
const set = (id: string): Block => ({ id, type: 'set', variable: 'A', value: 0 })
const atom = { kind: 'atom', atom: { kind: 'heldEmpty' } } as const

describe('factory editor', () => {
  it('counts nested bodies, both branches and functions at 30/31, including duplication', () => {
    const v = input()
    v.program = {
      main: [{ id: 'if', type: 'if', condition: atom, body: [{ id: 'w', type: 'while', condition: atom, body: [set('inner')] }], else: Array.from({ length: 10 }, (_, i) => set(`else${i}`)) }],
      functions: [{ id: 'f', icon: 'star', body: [{ id: 'r', type: 'repeat', count: 2, body: Array.from({ length: 15 }, (_, i) => set(`fn${i}`)) }] }],
    }
    const e = new FactoryEditorController(v, progress)
    expect(e.total).toBe(29)
    expect(e.duplicate('inner', { kind: 'function', id: 'f' })).toBe(true)
    expect(e.total).toBe(30)
    const before = e.doc
    expect(e.add(set('31'), { kind: 'else', id: 'if' })).toBe(false)
    expect(e.add(set('31'), { kind: 'function', id: 'f' })).toBe(false)
    expect(e.add(set('31'))).toBe(false)
    expect(e.duplicate('inner')).toBe(false)
    expect(e.duplicate('if')).toBe(false)
    expect(e.doc).toEqual(before)
    expect(e.undo()).toBe(true)
    expect(e.doc).toEqual(v.program)
    expect(e.duplicate('if')).toBe(false)
  })
  it('adds to each container, moves across branches and functions, and rejects invalid contexts atomically', () => {
    const e = new FactoryEditorController(input(), progress)
    const f = e.createFunction(true)!
    expect(e.add({ id: 'if', type: 'if', condition: atom, body: [] })).toBe(true)
    expect(e.add({ id: 'w', type: 'while', condition: atom, body: [] }, { kind: 'body', id: 'if' })).toBe(true)
    expect(e.add({ id: 'each', type: 'forEach', body: [] }, { kind: 'else', id: 'if' })).toBe(true)
    expect(e.add({ id: 'r', type: 'repeat', count: 2, body: [] }, { kind: 'body', id: 'w' })).toBe(true)
    expect(e.add(set('s'), { kind: 'body', id: 'r' })).toBe(true)
    expect(e.move('s', { kind: 'function', id: f }, 0)).toBe(true)
    expect(e.add({ id: 'ret', type: 'return', value: { kind: 'param' } }, { kind: 'function', id: f })).toBe(true)
    expect(e.add({ id: 'call', type: 'call', fn: f, arg: { kind: 'number', value: 2 } })).toBe(true)
    expect(e.add({ id: 'stop', type: 'breakForEach' }, { kind: 'body', id: 'each' })).toBe(true)
    expect(e.add({ id: 'on', type: 'on', signal: '○', body: [] })).toBe(true)
    expect(e.add(set('signal-set'), { kind: 'body', id: 'on' })).toBe(true)
    const before = e.doc
    expect(e.move('if', { kind: 'body', id: 'w' }, 0)).toBe(false)
    expect(e.move('stop', { kind: 'main' }, 0)).toBe(false)
    expect(e.move('ret', { kind: 'main' }, 0)).toBe(false)
    expect(e.add({ id: 'recursive', type: 'call', fn: f, arg: { kind: 'A' } }, { kind: 'function', id: f })).toBe(false)
    expect(e.removeFunction(f)).toBe(false)
    expect(e.doc).toEqual(before)
    expect(e.replace('call', { id: 'call', type: 'call', fn: f, arg: { kind: 'A' } })).toBe(true)
    expect(e.createFunction()).toBeDefined()
    expect(e.createFunction()).toBeUndefined()
    expect(e.editFunction(f, { id: f, icon: 'star', body: [] })).toBe(false)
    expect(e.editFunction(f, { id: f, icon: 'star', param: true, body: [{ id: 'new-return', type: 'return', value: { kind: 'beltCount' } }] })).toBe(true)
    expect(e.remove('call')).toBe(true)
    expect(e.removeFunction(f)).toBe(true)
    expect(e.undo()).toBe(true)
    expect(e.doc.functions.some(fn => fn.id === f)).toBe(true)
  })
  it('duplicates entire subtrees with fresh ids and independent ownership', () => {
    const e = new FactoryEditorController(input(), progress)
    const block: Block = { id: 'if', type: 'if', condition: atom, body: [set('yes')], else: [set('no')] }
    expect(e.add(block)).toBe(true)
    expect(e.duplicate('if')).toBe(true)
    block.body.push(set('external'))
    const [a, b] = e.doc.main
    expect(a.id).not.toBe(b.id)
    expect(e.total).toBe(6)
    expect(e.replace('yes', { ...set('yes'), type: 'set', value: 3, variable: 'A' })).toBe(true)
    expect(e.total).toBe(6)
    expect(e.remove('missing')).toBe(false)
  })
  it('edits start state without unit completion and enforces belt/pile/total limits and undo', () => {
    const e = new FactoryEditorController()
    for (let i = 0; i < 12; i++) expect(e.addBox('belt', i % 2 ? '○' : '◆')).toBe(true)
    expect(e.addBox('belt', '△')).toBe(false)
    for (let i = 0; i < 6; i++) expect(e.addBox('leaf', '△')).toBe(true)
    expect(e.addBox('leaf', '◆')).toBe(false)
    expect(e.addBox('moon', '◆')).toBe(false)
    expect(e.removeBox('belt', 0)).toBe(true)
    expect(e.addBox('moon', '◆')).toBe(true)
    expect(e.moveBox('belt', 0, 10)).toBe(true)
    expect(e.getSnapshot().input.start.belt.at(-1)?.shape).toBe('○')
    expect(e.undo()).toBe(true)
    expect(e.getSnapshot().input.start.belt[0].shape).toBe('○')
    expect(e.removeBox('sun', 0)).toBe(false)
    expect(e.moveBox('belt', -1, 0)).toBe(false)
    expect(e.addBox('sun', 'bad' as '◆')).toBe(false)
    const piles = new FactoryEditorController()
    for (let i = 0; i < 6; i++) expect(piles.addBox('sun', '◆')).toBe(true)
    expect(piles.addBox('sun', '◆')).toBe(false)
  })
  it('locks edits and undo, publishes subscriptions and isolates caller-owned inputs', () => {
    const v = input(), e = new FactoryEditorController(v, progress)
    let notifications = 0
    const unsubscribe = e.subscribe(() => notifications++)
    expect(e.add(set('s'))).toBe(true)
    v.program.main.push(set('external'))
    expect(e.total).toBe(1)
    e.setLocked(true)
    expect(e.undo()).toBe(false)
    expect(e.addBox('belt', '◆')).toBe(false)
    expect(e.loadDocument({ main: [], functions: [] })).toBe(false)
    e.setLocked(false)
    expect(e.undo()).toBe(true)
    expect(e.total).toBe(0)
    expect(notifications).toBe(4)
    unsubscribe()
    expect(e.undo()).toBe(false)
  })
  it('validates orders, target and signals and undoes input edits', () => {
    const e = new FactoryEditorController(input(), progress)
    expect(e.setOrders([0, 10, 2])).toBe(true)
    expect(e.setOrders(Array(6).fill(1))).toBe(false)
    expect(e.setOrders([-1])).toBe(false)
    expect(e.setTarget(10)).toBe(true)
    expect(e.setTarget(11)).toBe(false)
    expect(e.setSignals(Array(20).fill('○'))).toBe(true)
    expect(e.setSignals(Array(21).fill('○'))).toBe(false)
    expect(e.undo()).toBe(true)
    expect(e.getSnapshot().input.signals).toEqual([])
    expect(e.run().allowed).toBe(true)
  })
})


describe('factory project drafts', () => {
  function setup() {
    const values = new Map<string, string>()
    const storage = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value) }, removeItem: (key: string) => { values.delete(key) } }
    const repository = createProgressStore(storage)
    return { storage, repository, controller: new FactoryProjectsController(repository) }
  }
  it('saves explicitly, tracks edits and undo, and keeps names out of learning history', () => {
    const { controller: c, repository, storage } = setup()
    c.open(undefined, undefined, 'Name')
    expect(storage.getItem(projectsKey)).toBeNull()
    expect(c.getSnapshot().dirty).toBe(true)
    expect(c.requestLeave('home')).toBe(false)
    c.cancelLeave(); expect(c.getSnapshot().leaving).toBeUndefined()
    expect(c.save()).toBe(true)
    expect(c.getSnapshot()).toMatchObject({ dirty: false, notice: 'saved' })
    c.editor!.addBox('belt', '◆')
    expect(c.getSnapshot()).toMatchObject({ dirty: true, notice: undefined })
    c.editor!.undo()
    expect(c.getSnapshot().dirty).toBe(false)
    expect(c.requestLeave('list')).toBe(true)
    c.rename('Name with space ')
    expect(c.getSnapshot().name).toBe('Name with space ')
    c.save()
    expect(c.getSnapshot().name).toBe('Name with space')
    expect(repository.getHistory().events).toEqual([])
    c.dispose()
  })
  it('opens previous snapshots as independent dirty drafts and never changes their sources', () => {
    const { controller: c, repository, storage } = setup()
    c.open(undefined, undefined, 'Factory'); c.save()
    c.editor!.addBox('belt', '○'); c.save()
    const project = repository.getProjects().projects[0]
    const first = structuredClone(project.snapshots[0])
    c.close(); c.open(project.id, first.id)
    expect(c.getSnapshot().dirty).toBe(true)
    expect(c.editor!.getSnapshot().input.start.belt).toEqual([])
    c.editor!.addBox('moon', '◆')
    expect(repository.getProjects().projects[0].snapshots[0]).toEqual(first)
    c.save(); c.close()
    const reconnect = new FactoryProjectsController(createProgressStore(storage))
    reconnect.open(project.id)
    expect(reconnect.editor!.getSnapshot().input.start.piles.moon).toHaveLength(1)
    expect(reconnect.getSnapshot().dirty).toBe(false)
    expect(repository.getProjects().projects[0].snapshots[0]).toEqual(first)
    c.dispose(); reconnect.dispose()
  })
  it('retains a failed draft, keeps exit pending, and retries the same content without duplicating it', () => {
    const { storage } = setup(); let fail = true
    const repository = createProgressStore({ ...storage, setItem(key, value) { if (fail && key === projectsKey) throw Error('denied'); storage.setItem(key, value) } })
    const c = new FactoryProjectsController(repository)
    c.open(undefined, undefined, 'Memory'); c.editor!.addBox('belt', '◆')
    c.requestLeave('home')
    expect(c.save()).toBe(false)
    expect(c.getSnapshot()).toMatchObject({ dirty: true, notice: 'unavailable', leaving: 'home' })
    expect(c.editor!.getSnapshot().input.start.belt).toHaveLength(1)
    c.rename('Memory changed')
    expect(c.getSnapshot().volatile).toBe(true)
    fail = false
    expect(c.save()).toBe(true)
    expect(c.getSnapshot().dirty).toBe(false)
    expect(createProgressStore(storage).getProjects().projects[0].snapshots).toHaveLength(1)
    c.dispose()
  })
  it('keeps failed projects unsaved after returning to the list and reopening, until persistence succeeds', () => {
    const { storage } = setup()
    let fail = false
    const repository = createProgressStore({ ...storage, setItem(key, value) { if (fail && key === projectsKey) throw Error('denied'); storage.setItem(key, value) } })
    const c = new FactoryProjectsController(repository)
    c.open(undefined, undefined, 'Saved')
    expect(c.save()).toBe(true)
    const savedId = c.getSnapshot().projectId!
    c.close()
    fail = true
    c.open(undefined, undefined, 'Memory')
    c.editor!.addBox('belt', '◆')
    expect(c.save()).toBe(false)
    const failedId = c.getSnapshot().projectId!
    expect(c.requestLeave('list')).toBe(false)
    c.close()
    expect(c.getSnapshot().projects.map(p => p.id)).toContain(failedId)
    expect(c.open(savedId)).toBe(true)
    expect(c.getSnapshot()).toMatchObject({ dirty: false, volatile: false })
    expect(c.requestLeave('list')).toBe(true)
    c.close()
    expect(c.open(failedId)).toBe(true)
    expect(c.editor!.getSnapshot().input.start.belt).toHaveLength(1)
    expect(c.getSnapshot()).toMatchObject({ dirty: true, volatile: true, notice: undefined })
    expect(c.requestLeave('home')).toBe(false)
    expect(c.getSnapshot().leaving).toBe('home')
    c.cancelLeave()
    expect(c.save()).toBe(false)
    c.close(); c.open(failedId)
    expect(c.getSnapshot()).toMatchObject({ dirty: true, volatile: true, notice: undefined })
    expect(c.requestLeave('list')).toBe(false)
    fail = false
    expect(c.save()).toBe(true)
    c.close(); c.open(failedId)
    expect(c.getSnapshot()).toMatchObject({ dirty: false, volatile: false })
    expect(c.requestLeave('home')).toBe(true)
    expect(createProgressStore(storage).getProjects().projects.find(p => p.id === failedId)?.snapshots).toHaveLength(1)
    // A failed update to an already persisted project must also stay dirty on reopen.
    fail = true
    c.editor!.addBox('moon', '○')
    expect(c.save()).toBe(false)
    c.close(); c.open(failedId)
    expect(c.getSnapshot()).toMatchObject({ dirty: true, volatile: true, notice: undefined })
    expect(c.requestLeave('list')).toBe(false)
    c.dispose()
    const reopened = new FactoryProjectsController(repository)
    reopened.open(failedId)
    expect(reopened.getSnapshot()).toMatchObject({ dirty: true, volatile: true, notice: undefined })
    expect(reopened.requestLeave('home')).toBe(false)
    reopened.dispose()
  })
  it('preserves locked snapshots after progress is reduced, allowing setup but refusing execution', () => {
    const { controller: c, repository } = setup()
    factoryUnits[0].forEach(stage => repository.completeStage(stage.id, 1, []))
    c.open(undefined, undefined, 'Locked')
    expect(c.editor!.add({ id: 'take', type: 'takeBelt' })).toBe(true)
    c.save(); const id = c.getSnapshot().projectId!
    // Simulate a restored save in a device/session without the corresponding progress.
    const projectDoc = repository.getProjects()
    const locked = createProgressStore({ getItem: key => key === projectsKey ? JSON.stringify(projectDoc) : null, setItem() {} })
    const next = new FactoryProjectsController(locked)
    next.open(id)
    expect(next.editor!.doc.main).toHaveLength(1)
    expect(next.editor!.getSnapshot().requiredUnits).toEqual([1])
    expect(next.editor!.run().allowed).toBe(false)
    expect(next.save()).toBe(true)
    expect(locked.getProjects()).toEqual(projectDoc)
    c.dispose(); next.dispose()
  })
})
