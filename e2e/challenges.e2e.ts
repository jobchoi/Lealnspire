import { expect, Game, test } from './helpers'

/** T84-6: 맞히면 완료 도장, 선택 도전은 완료 뒤 펼쳐 보고 실제로 실행한 방법으로 판정. 미달성은 아무 표시 없음 */
test('2번: 오른쪽으로 풀면 도장 + "하나 했어요", 왼쪽으로만 다시 풀면 도전 성공 — 새로고침 뒤에도 남는다', async ({ page }) => {
  const g = new Game(page)
  await g.fresh()
  await page.evaluate(() => localStorage.setItem('lealnspire.progress.v2', JSON.stringify({ version: 2, stages: { 1: { completed: true, bestStars: 3 } } })))
  await page.reload()
  await g.press(g.button('스테이지 목록'))
  await g.press(page.locator('.stage-card').nth(1))
  await g.speed('빠르게')
  await expect(page.getByRole('button', { name: '더 해 볼까?' }), '완료 전에는 도전이 보이지 않음').toHaveCount(0)
  await g.build('F F R F')
  const first = await g.runToEnd()
  expect(first).toContain('해냈어요')
  expect(first, '첫 방법만으로는 도전 성공 아님').not.toContain('도전 성공')
  expect(first, '실패·별 문구 없음').not.toMatch(/별 \d개|실패/)
  await g.press(g.dialog.getByRole('button', { name: '닫기' }))
  await g.press(page.getByRole('button', { name: '더 해 볼까?' }))
  await expect(page.getByText('왼쪽으로도, 오른쪽으로도 돌아서 풀기')).toBeVisible()
  await expect(page.getByText(/하나 했어요/)).toBeVisible()
  await page.screenshot({ path: 'e2e-results/screens/challenge-partial.png' })
  await g.press(g.button('처음으로'))
  await g.clear()
  await g.build('F F L L L F')
  expect(await g.runToEnd()).toContain('도전 성공')
  await page.screenshot({ path: 'e2e-results/screens/challenge-done.png' })
  await page.reload()
  await g.press(g.button('스테이지 목록'))
  await g.press(page.locator('.stage-card').nth(1))
  await g.press(page.getByRole('button', { name: '더 해 볼까?' }))
  await expect(page.getByText(/도전 성공/), '새로고침 뒤에도 달성 유지').toBeVisible()
})

test('실행하지 않는 회전은 인정하지 않는다: 도착 뒤에 놓인 왼쪽 회전은 "왼쪽으로 풀기"가 아니다', async ({ page }) => {
  const g = new Game(page)
  await g.fresh()
  await page.evaluate(() => localStorage.setItem('lealnspire.progress.v2', JSON.stringify({ version: 2, stages: { 1: { completed: true, bestStars: 3 } } })))
  await page.reload()
  await g.press(g.button('스테이지 목록'))
  await g.press(page.locator('.stage-card').nth(1))
  await g.speed('빠르게')
  await g.build('F F R F L')
  const text = await g.runToEnd()
  expect(text).toContain('해냈어요')
  expect(text).not.toContain('도전 성공')
})

